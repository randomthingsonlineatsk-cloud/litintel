// LitIntel weekly watch. Runs in GitHub Actions (or locally with `node watch/run.mjs`).
// Reads watch/searches.json, finds records added to PubMed and Europe PMC since the last run,
// writes a Markdown digest to reports/, and remembers what it has already reported in watch/state.json.
