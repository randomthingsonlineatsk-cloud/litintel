import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const C = require(path.join(ROOT, 'core.js'));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function pubmedSince(query, since, opts, fetchFn) {
  const base = 'https://eutils.ncbi.nlm.nih.gov/entrez/eutils/';
  const common = '&tool=litintel' + (opts.email ? '&email=' + encodeURIComponent(opts.email) : '') + (opts.apiKey ? '&api_key=' + encodeURIComponent(opts.apiKey) : '');
  const es = await (await fetchFn(base + 'esearch.fcgi?db=pubmed&retmode=json&retmax=500&datetype=edat&mindate=' + since.replace(/-/g, '/') + '&maxdate=3000&term=' + encodeURIComponent(query) + common)).json();
  const ids = es.esearchresult?.idlist || [];
  const records = [];
  for (let i = 0; i < ids.length; i += 200) {
    await sleep(opts.apiKey ? 120 : 400);
    const sum = await (await fetchFn(base + 'esummary.fcgi?db=pubmed&retmode=json&id=' + ids.slice(i, i + 200).join(',') + common)).json();
    for (const id of sum.result?.uids || []) {
      const d = sum.result[id];
      const doi = (d.articleids || []).find((a) => a.idtype === 'doi');
      records.push(C.makeRecord({
        title: d.title, authors: (d.authors || []).map((a) => a.name), year: String(d.pubdate || '').slice(0, 4), journal: d.fulljournalname || d.source,
        doi: doi && doi.value, pmid: id, pubTypes: d.pubtype || [], sources: ['PubMed'],
      }));
    }
  }
  return { source: 'PubMed', total: Number(es.esearchresult?.count || 0), records };
}

export async function main({ fetchFn = globalThis.fetch, root = ROOT, now = new Date() } = {}) {
  const cfgPath = path.join(root, 'watch', 'searches.json');
  const statePath = path.join(root, 'watch', 'state.json');
  const cfg = JSON.parse(await readFile(cfgPath, 'utf8'));
  const state = existsSync(statePath) ? JSON.parse(await readFile(statePath, 'utf8')) : { lastRun: null, seen: [] };
  const fallback = new Date(now.getTime() - 7 * 864e5).toISOString().slice(0, 10);
  const since = state.lastRun ? state.lastRun.slice(0, 10) : fallback;
  const opts = { email: cfg.email && !/example\.com$/.test(cfg.email) ? cfg.email : '', apiKey: process.env.NCBI_API_KEY || '' };

  const runs = []; let all = [];
  for (const s of cfg.searches || []) {
    try {
      const res = s.source === 'pubmed' ? await pubmedSince(s.query, since, opts, fetchFn)
        : await C.searchEuropePMC({ query: s.query, since, max: 500, fetch: fetchFn });
      runs.push({ source: res.source, query: s.query, total: res.total, retrieved: res.records.length });
      all = all.concat(res.records);
    } catch (e) {
      runs.push({ source: s.source, query: s.query, error: String(e.message || e) });
    }
  }
  const merged = C.dedupe(all).records;
  const fresh = C.newRecordsSince(merged, state.seen);
  const day = now.toISOString().slice(0, 10);

  const L = [`# ${cfg.project || 'LitIntel watch'}: new records, ${day}`, '', `Records added to the databases since ${since}. Generated by LitIntel ${C.VERSION}.`, '',
    '| Database | Query | Hits since last run | Note |', '|---|---|---|---|'];
  runs.forEach((r) => L.push(`| ${r.source} | \`${r.query.replace(/\|/g, '\\|')}\` | ${r.error ? '—' : r.total} | ${r.error ? 'Error: ' + r.error.replace(/\|/g, '/') : ''} |`));
  L.push('', `**${fresh.length} new record${fresh.length === 1 ? '' : 's'}** after removing duplicates and anything reported before.`, '');
  fresh.forEach((r, i) => {
    L.push(`${i + 1}. **${r.title}**  `, `   ${r.authors.slice(0, 3).join(', ')}${r.authors.length > 3 ? ' et al.' : ''}. *${r.journal || 'Unknown source'}* ${r.year || ''}. ${C.recordUrl(r)}${r.pubTypes.length ? '  \n   Type: ' + r.pubTypes.slice(0, 3).join(', ') : ''}`);
  });
  L.push('', 'Screen these in LitIntel: open your project, go to Watch and run the check, or search for them directly.');

  await mkdir(path.join(root, 'reports'), { recursive: true });
  const reportPath = path.join(root, 'reports', day + '.md');
  await writeFile(reportPath, L.join('\n') + '\n');
  const anyOk = runs.some((r) => !r.error);
  if (anyOk) {
    const seen = Array.from(new Set(state.seen.concat(fresh.map((r) => r.id)))).slice(-20000);
    await writeFile(statePath, JSON.stringify({ lastRun: now.toISOString(), seen }, null, 1) + '\n');
  }
  const summary = { day, since, newCount: fresh.length, errors: runs.filter((r) => r.error).length, reportPath: path.relative(root, reportPath) };
  if (process.env.GITHUB_OUTPUT) await writeFile(process.env.GITHUB_OUTPUT, `new_count=${summary.newCount}\nreport=${summary.reportPath}\n`, { flag: 'a' });
  console.log(JSON.stringify(summary));
  if (!anyOk) process.exitCode = 1;
  return summary;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
